using System;
using System.Runtime.InteropServices;
using System.Text;

namespace Tippli.Windows.Interop;

/// <summary>Virtual key codes used by Tippli.</summary>
internal static class VK
{
    public const int BACK = 0x08, TAB = 0x09, CLEAR = 0x0C, RETURN = 0x0D;
    public const int SHIFT = 0x10, CONTROL = 0x11, MENU = 0x12, PAUSE = 0x13, CAPITAL = 0x14;
    public const int KANA = 0x15, JUNJA = 0x17, FINAL = 0x18, KANJI = 0x19, CONVERT = 0x1C, NONCONVERT = 0x1D, ACCEPT = 0x1E, MODECHANGE = 0x1F;
    public const int ESCAPE = 0x1B, SPACE = 0x20, PRIOR = 0x21, NEXT = 0x22, END = 0x23, HOME = 0x24;
    public const int LEFT = 0x25, UP = 0x26, RIGHT = 0x27, DOWN = 0x28, SELECT = 0x29, PRINT = 0x2A, EXECUTE = 0x2B, SNAPSHOT = 0x2C;
    public const int INSERT = 0x2D, DELETE = 0x2E, HELP = 0x2F;
    public const int B = 0x42, C = 0x43, H = 0x48, J = 0x4A, K = 0x4B, V = 0x56;
    public const int LWIN = 0x5B, RWIN = 0x5C, APPS = 0x5D, SLEEP = 0x5F;
    public const int F1 = 0x70, F24 = 0x87;
    public const int NUMLOCK = 0x90, SCROLL = 0x91;
    public const int LSHIFT = 0xA0, RSHIFT = 0xA1, LCONTROL = 0xA2, RCONTROL = 0xA3, LMENU = 0xA4, RMENU = 0xA5;
    public const int BROWSER_BACK = 0xA6, LAUNCH_APP2 = 0xB7;
    public const int PROCESSKEY = 0xE5, PACKET = 0xE7;

    public static bool IsModifier(int vk) => vk is SHIFT or CONTROL or MENU or LSHIFT or RSHIFT or LCONTROL or RCONTROL or LMENU or RMENU
        or LWIN or RWIN or CAPITAL or NUMLOCK or SCROLL;

    public static bool IsNavigation(int vk) => vk is PRIOR or NEXT or END or HOME or LEFT or UP or RIGHT or DOWN or INSERT or CLEAR;

    public static bool IsFunctionOrMedia(int vk) => (vk >= F1 && vk <= F24) || (vk >= BROWSER_BACK && vk <= LAUNCH_APP2)
        || vk is PAUSE or SNAPSHOT or SLEEP or SELECT or PRINT or EXECUTE or HELP;

    /// <summary>Keys that need KEYEVENTF_EXTENDEDKEY when injected.</summary>
    public static bool IsExtended(int vk) => vk is PRIOR or NEXT or END or HOME or LEFT or UP or RIGHT or DOWN or INSERT or DELETE
        or RCONTROL or RMENU or LWIN or RWIN or APPS or NUMLOCK or SNAPSHOT;
}

/// <summary>Win32 declarations. Structs are laid out for both x86 and x64 (pointer-sized fields are IntPtr/UIntPtr).</summary>
internal static class NativeMethods
{
    // ---- low level hooks ------------------------------------------------------------------------------

    public const int WH_KEYBOARD_LL = 13;
    public const int WH_MOUSE_LL = 14;
    public const int HC_ACTION = 0;

    public const int WM_KEYDOWN = 0x0100;
    public const int WM_KEYUP = 0x0101;
    public const int WM_SYSKEYDOWN = 0x0104;
    public const int WM_SYSKEYUP = 0x0105;
    public const int WM_LBUTTONDOWN = 0x0201;
    public const int WM_RBUTTONDOWN = 0x0204;
    public const int WM_MBUTTONDOWN = 0x0207;
    public const int WM_XBUTTONDOWN = 0x020B;
    public const int WM_HOTKEY = 0x0312;
    public const int WM_MOUSEACTIVATE = 0x0021;
    public const int MA_NOACTIVATE = 3;

    public const uint LLKHF_EXTENDED = 0x01;
    public const uint LLKHF_LOWER_IL_INJECTED = 0x02;
    public const uint LLKHF_INJECTED = 0x10;
    public const uint LLKHF_ALTDOWN = 0x20;
    public const uint LLKHF_UP = 0x80;
    public const uint LLMHF_INJECTED = 0x01;

    [StructLayout(LayoutKind.Sequential)]
    public struct KBDLLHOOKSTRUCT
    {
        public uint vkCode;
        public uint scanCode;
        public uint flags;
        public uint time;
        public UIntPtr dwExtraInfo;
    }

    [StructLayout(LayoutKind.Sequential)]
    public struct POINT
    {
        public int X;
        public int Y;
    }

    [StructLayout(LayoutKind.Sequential)]
    public struct MSLLHOOKSTRUCT
    {
        public POINT pt;
        public uint mouseData;
        public uint flags;
        public uint time;
        public UIntPtr dwExtraInfo;
    }

    [UnmanagedFunctionPointer(CallingConvention.Winapi)]
    public delegate IntPtr LowLevelHookProc(int nCode, IntPtr wParam, IntPtr lParam);

    [DllImport("user32.dll", SetLastError = true)]
    public static extern IntPtr SetWindowsHookEx(int idHook, LowLevelHookProc lpfn, IntPtr hMod, uint dwThreadId);

    [DllImport("user32.dll", SetLastError = true)]
    [return: MarshalAs(UnmanagedType.Bool)]
    public static extern bool UnhookWindowsHookEx(IntPtr hhk);

    [DllImport("user32.dll")]
    public static extern IntPtr CallNextHookEx(IntPtr hhk, int nCode, IntPtr wParam, IntPtr lParam);

    [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    public static extern IntPtr GetModuleHandle(string? lpModuleName);

    // ---- keyboard state / translation -----------------------------------------------------------------

    [DllImport("user32.dll")]
    public static extern short GetAsyncKeyState(int vKey);

    [DllImport("user32.dll")]
    public static extern short GetKeyState(int nVirtKey);

    /// <summary>wFlags bit 2 (0x4): do not change the keyboard state (dead keys), Windows 10 1607+.</summary>
    public const uint TOUNICODE_NO_STATE_CHANGE = 0x4;

    [DllImport("user32.dll", CharSet = CharSet.Unicode)]
    public static extern int ToUnicodeEx(uint wVirtKey, uint wScanCode, byte[] lpKeyState, [Out] char[] pwszBuff, int cchBuff,
        uint wFlags, IntPtr dwhkl);

    [DllImport("user32.dll")]
    public static extern IntPtr GetKeyboardLayout(uint idThread);

    public const uint MAPVK_VK_TO_VSC = 0;

    [DllImport("user32.dll", EntryPoint = "MapVirtualKeyW")]
    public static extern uint MapVirtualKey(uint uCode, uint uMapType);

    // ---- SendInput --------------------------------------------------------------------------------------

    public const uint INPUT_MOUSE = 0;
    public const uint INPUT_KEYBOARD = 1;
    public const uint KEYEVENTF_EXTENDEDKEY = 0x0001;
    public const uint KEYEVENTF_KEYUP = 0x0002;
    public const uint KEYEVENTF_UNICODE = 0x0004;
    public const uint KEYEVENTF_SCANCODE = 0x0008;

    /// <summary>INPUT: 28 bytes on x86, 40 bytes on x64 (the union is 8-byte aligned there).</summary>
    [StructLayout(LayoutKind.Sequential)]
    public struct INPUT
    {
        public uint type;
        public InputUnion U;
    }

    [StructLayout(LayoutKind.Explicit)]
    public struct InputUnion
    {
        [FieldOffset(0)] public MOUSEINPUT mi;
        [FieldOffset(0)] public KEYBDINPUT ki;
        [FieldOffset(0)] public HARDWAREINPUT hi;
    }

    [StructLayout(LayoutKind.Sequential)]
    public struct MOUSEINPUT
    {
        public int dx;
        public int dy;
        public uint mouseData;
        public uint dwFlags;
        public uint time;
        public IntPtr dwExtraInfo;
    }

    [StructLayout(LayoutKind.Sequential)]
    public struct KEYBDINPUT
    {
        public ushort wVk;
        public ushort wScan;
        public uint dwFlags;
        public uint time;
        public IntPtr dwExtraInfo;
    }

    [StructLayout(LayoutKind.Sequential)]
    public struct HARDWAREINPUT
    {
        public uint uMsg;
        public ushort wParamL;
        public ushort wParamH;
    }

    [DllImport("user32.dll", SetLastError = true)]
    public static extern uint SendInput(uint nInputs, [In] INPUT[] pInputs, int cbSize);

